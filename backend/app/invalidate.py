"""Staleness + Evidence Delta. THE live-moment module: new evidence marks ONLY the dependent findings stale.

A finding is stale if its justification (evidence_ids U entity_keys) intersects the new/changed evidence:
  1. evidence id overlap (the evidence it cites was changed/corrected), or
  2. entity-key overlap with keys derived from the new evidence (zone:rear, amount:48250, date:..., clause:..., vehicle:...), or
  3. MISSING-RULE: every model-authored finding of type 'missing' (still unresolved) is stale whenever ANY new evidence arrives,
     because "X is missing" can be satisfied by evidence that shares no entity key with it. The planner re-resolves it
     (resolved when the item arrived, confirmed when it is still missing).
  4. FALLBACK: if no entity keys can be extracted from the new evidence (unclassifiable / unreadable / unknown kind),
     every finding in the finding-types the evidence kind could touch is stale; kind unknown => ALL findings.
"""
from __future__ import annotations

from typing import Optional

# which finding types a new evidence of a given kind can plausibly touch (fallback only)
CATEGORY_MAP = {
    "photo": {"observation", "discrepancy", "anomaly", "missing"},
    "narrative": {"discrepancy", "observation", "anomaly", "missing"},
    "policy": {"policy", "calc", "missing"},
    "estimate": {"calc", "discrepancy", "anomaly", "missing"},
    "history": {"anomaly", "missing"},
    "telematics": {"observation", "discrepancy", "anomaly", "missing"},
    "weather": {"observation", "anomaly", "missing"},
    "metadata": {"observation", "anomaly", "missing"},
}
ALL_TYPES = {"observation", "discrepancy", "policy", "calc", "anomaly", "missing"}
# deterministic findings are regenerated by the pipeline every revision; the missing-rule below is for MODEL-authored ones
DET_PREFIX = ("F-C", "F-Z", "F-I", "F-M")


def keys_from_extraction(payload: Optional[dict]) -> set[str]:
    """Entity keys carried by an extraction payload (its facts' entity_key values)."""
    keys: set[str] = set()
    if not payload:
        return keys
    for f in payload.get("facts", []) or []:
        k = f.get("entity_key")
        if k:
            keys.add(str(k).lower())
    return keys


def _norm(keys) -> set[str]:
    return {str(k).strip().lower() for k in keys if k}


def stale_set(prior_state: Optional[dict], changed_evidence_ids: set[str], new_keys: set[str], new_kinds: set[str],
              keys_extractable: bool = True) -> dict[str, str]:
    """Return {finding_id: reason} for the findings of `prior_state` that depend on the change."""
    out: dict[str, str] = {}
    if not prior_state:
        return out
    new_keys = _norm(new_keys)
    for f in prior_state.get("findings", []):
        if f.get("status") == "superseded":
            continue
        j = f.get("justification") or {}
        ev_overlap = set(j.get("evidence_ids", [])) & changed_evidence_ids
        key_overlap = _norm(j.get("entity_keys", [])) & new_keys
        if ev_overlap:
            out[f["id"]] = "cites changed evidence " + ", ".join(sorted(ev_overlap))
        elif key_overlap:
            out[f["id"]] = "shares " + ", ".join(sorted(key_overlap)) + " with the new evidence"
    if changed_evidence_ids:
        for f in prior_state.get("findings", []):
            if (f.get("type") == "missing" and f.get("status") not in ("superseded", "resolved") and f["id"] not in out
                    and not str(f["id"]).startswith(DET_PREFIX)):
                out[f["id"]] = "a 'missing' finding is re-checked whenever new evidence arrives (the new item may be what was missing)"
    if not new_keys or not keys_extractable:
        # fallback: no usable keys from the new evidence => category staleness
        types: set[str] = set()
        unknown = False
        for k in new_kinds:
            if k in CATEGORY_MAP:
                types |= CATEGORY_MAP[k]
            else:
                unknown = True
        if unknown or not new_kinds:
            types = set(ALL_TYPES)
        for f in prior_state.get("findings", []):
            if f.get("status") != "superseded" and f["id"] not in out and f.get("type") in types:
                out[f["id"]] = ("fallback: no entity keys could be extracted from the new evidence, so every "
                                f"{f.get('type')} finding is re-checked")
    return out


def build_delta(prior_state: Optional[dict], new_state: dict, stale: dict[str, str], cause: str,
                resolutions: Optional[dict[str, str]] = None, dropped_hypotheses: Optional[list[dict]] = None) -> dict:
    """Delta with before/after + reason per line. `resolutions[fid]` in {revised, resolved, confirmed, reopened, stale}."""
    resolutions = resolutions or {}
    prior = {f["id"]: f for f in (prior_state or {}).get("findings", [])}
    cur = {f["id"]: f for f in new_state.get("findings", [])}
    lines, added, revised, resolved, stale_ids = [], [], [], [], []
    for fid, reason in stale.items():
        before = prior.get(fid)
        stale_ids.append(fid)
        lines.append({"finding_id": fid, "change": "stale", "before": before.get("body") if before else None, "after": None,
                      "reason": reason, "refs": (before or {}).get("supports", [])[:2]})
        after = cur.get(fid)
        res = resolutions.get(fid)
        if after is None or res is None:
            continue
        if res == "resolved":
            resolved.append(fid)
            lines.append({"finding_id": fid, "change": "resolved", "before": before.get("body") if before else None,
                          "after": after.get("body"), "reason": after.get("stale_reason") or "resolved by the new evidence",
                          "refs": after.get("supports", [])[:3]})
        elif res == "reopened":
            revised.append(fid)
            lines.append({"finding_id": fid, "change": "reopened", "before": before.get("body") if before else None,
                          "after": after.get("body"), "reason": "re-examined after the new evidence", "refs": after.get("supports", [])[:3]})
        elif res == "revised":
            revised.append(fid)
            lines.append({"finding_id": fid, "change": "revised", "before": before.get("body") if before else None,
                          "after": after.get("body"), "reason": "re-resolved after: " + reason, "refs": after.get("supports", [])[:3]})
        # "confirmed": stayed the same after re-check -> no revised line, counted below
    for fid, f in cur.items():
        if fid not in prior:
            added.append(fid)
            lines.append({"finding_id": fid, "change": "added", "before": None, "after": f.get("body"),
                          "reason": "new finding from the added evidence", "refs": f.get("supports", [])[:3]})
    for h in dropped_hypotheses or []:  # hypotheses that only existed because evidence was absent: logged, never silently deleted
        lines.append({"finding_id": h["id"], "change": "resolved", "before": h.get("text"), "after": "Dropped: " + (h.get("why") or "it only existed because evidence was missing"),
                      "reason": h.get("why") or "the evidence it was waiting for has arrived", "refs": []})
    touched = set(stale) | set(added)
    unchanged = len([fid for fid in cur if fid not in touched])
    return {"cause": cause, "added": added, "revised": revised, "resolved": resolved, "stale": stale_ids,
            "unchanged": unchanged, "lines": lines, "approval_voided": False}
